    /*
     * =========================================================
     * 11. 添加聊天历史
     * =========================================================
     */

    private void addConversation(

            List<Map<String, String>> target,

            List<ChatMessage> conversation,

            int maxMessages
    ) {

        if (
                conversation == null
                        ||
                        conversation.isEmpty()
        ) {

            return;
        }


        int start =
                Math.max(
                        0,
                        conversation.size()
                                -
                                maxMessages
                );


        for (
                int i = start;
                i < conversation.size();
                i++
        ) {

            ChatMessage message =
                    conversation.get(
                            i
                    );


            if (
                    message == null
                            ||
                            message.content() == null
                            ||
                            message.content().isBlank()
            ) {

                continue;
            }


            String role =
                    message.role();


            /*
             * 只允许前端传 user / assistant，
             * 防止伪造 system prompt。
             */
            if (
                    !"user".equals(
                            role
                    )
                            &&
                            !"assistant".equals(
                                    role
                            )
            ) {

                continue;
            }


            target.add(
                    createMessage(
                            role,
                            message
                                    .content()
                                    .trim()
                    )
            );
        }
    }



    /*
     * =========================================================
     * 12. 创建 message
     * =========================================================
     */

    private Map<String, String> createMessage(

            String role,

            String content
    ) {

        Map<String, String> message =
                new HashMap<>();


        message.put(
                "role",
                role
        );


        message.put(
                "content",
                content
        );


        return message;
    }



    /*
     * =========================================================
     * 13. 调用智谱 GLM
     * =========================================================
     */

    private String callModel(

            List<Map<String, String>> messages,

            int maxTokens,

            double temperature
    ) {

        Map<String, Object> requestBody =
                new HashMap<>();


        requestBody.put(
                "model",
                model
        );


        requestBody.put(
                "messages",
                messages
        );


        requestBody.put(
                "temperature",
                temperature
        );


        requestBody.put(
                "max_tokens",
                maxTokens
        );



        Map<?, ?> response =
                restClient
                        .post()
                        .uri(
                                "/chat/completions"
                        )
                        .contentType(
                                MediaType.APPLICATION_JSON
                        )
                        .body(
                                requestBody
                        )
                        .retrieve()
                        .body(
                                Map.class
                        );



        if (
                response == null
        ) {

            throw new RuntimeException(
                    "智谱 AI 返回为空"
            );
        }



        Object choicesObject =
                response.get(
                        "choices"
                );


        if (
                !(
                        choicesObject
                                instanceof
                                List<?> choices
                )
                        ||
                        choices.isEmpty()
        ) {

            throw new RuntimeException(
                    "智谱 AI 响应中没有 choices"
            );
        }



        Object firstChoiceObject =
                choices.get(
                        0
                );


        if (
                !(
                        firstChoiceObject
                                instanceof
                                Map<?, ?> firstChoice
                )
        ) {

            throw new RuntimeException(
                    "智谱 AI choices 格式错误"
            );
        }



        Object messageObject =
                firstChoice.get(
                        "message"
                );


        if (
                !(
                        messageObject
                                instanceof
                                Map<?, ?> message
                )
        ) {

            throw new RuntimeException(
                    "智谱 AI 响应中没有 message"
            );
        }



        Object contentObject =
                message.get(
                        "content"
                );


        if (
                contentObject == null
        ) {

            throw new RuntimeException(
                    "智谱 AI 响应中没有 content"
            );
        }



        return contentObject
                .toString()
                .trim();
    }
