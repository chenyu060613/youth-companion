    /*
     * =========================================================
     * 8. 解析 task_plan JSON
     * =========================================================
     */

    private DailyTaskPlanResult parseTaskPlanJson(
            String raw
    ) {

        if (
                raw == null
                        ||
                        raw.isBlank()
        ) {

            throw new RuntimeException(
                    "任务日程 AI 返回为空"
            );
        }


        String cleaned =
                raw
                        .trim()
                        .replace(
                                "```json",
                                ""
                        )
                        .replace(
                                "```JSON",
                                ""
                        )
                        .replace(
                                "```",
                                ""
                        )
                        .trim();



        /*
         * 有些模型偶尔会在 JSON 前后
         * 加一句解释。
         *
         * 尝试只截取最外层 JSON。
         */
        int firstBrace =
                cleaned.indexOf(
                        "{"
                );


        int lastBrace =
                cleaned.lastIndexOf(
                        "}"
                );


        if (
                firstBrace >= 0
                        &&
                        lastBrace > firstBrace
        ) {

            cleaned =
                    cleaned.substring(
                            firstBrace,
                            lastBrace + 1
                    );
        }



        try {

            JsonMapper mapper =
                    JsonMapper
                            .builder()
                            .build();


            DailyTaskPlanResult parsed =
                    mapper.readValue(
                            cleaned,
                            DailyTaskPlanResult.class
                    );


            if (
                    parsed == null
            ) {

                throw new RuntimeException(
                        "任务日程结果为空"
                );
            }



            String reply =
                    parsed.reply() == null
                            ?
                            "可以，我们把你自己的任务拆轻一点，再在中间留一点恢复空间。"
                            :
                            parsed.reply().trim();



            List<String> plan =
                    cleanStringList(
                            parsed.plan(),
                            6
                    );



            List<String> recommendations =
                    cleanStringList(
                            parsed.recommendations(),
                            3
                    );



            if (
                    plan.isEmpty()
            ) {

                throw new RuntimeException(
                        "任务日程 plan 为空"
                );
            }



            if (
                    recommendations.isEmpty()
            ) {

                throw new RuntimeException(
                        "任务日程 recommendations 为空"
                );
            }



            return new DailyTaskPlanResult(

                    reply,

                    plan,

                    recommendations
            );


        } catch (Exception e) {

            throw new RuntimeException(
                    "无法解析任务日程 AI 返回："
                            +
                            cleaned,
                    e
            );
        }
    }



    /*
     * =========================================================
     * 9. 清理模型返回的字符串数组
     * =========================================================
     */

    private List<String> cleanStringList(

            List<String> source,

            int maxItems
    ) {

        List<String> result =
                new ArrayList<>();


        if (
                source == null
        ) {

            return result;
        }


        for (
                String item
                :
                source
        ) {

            if (
                    item == null
                            ||
                            item.isBlank()
            ) {

                continue;
            }


            result.add(
                    item.trim()
            );


            if (
                    result.size()
                            >=
                            maxItems
            ) {

                break;
            }
        }


        return result;
    }



